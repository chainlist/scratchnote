/**
 * Plugin icons are SVG markup: a whole `<svg>`, or only what goes inside a
 * 24 by 24 Lucide icon (its paths), which is drawn with Lucide's stroke so
 * it sits with the app's own icons. A plugin copies the markup of the icon
 * it wants from lucide.dev.
 */

/** Lucide's puzzle piece, for a plugin that names no icon. */
const PUZZLE =
	'<path d="M15.39 4.39a1 1 0 0 0 1.68-.474 2.5 2.5 0 1 1 3.014 3.015 1 1 0 0 0-.474 1.68l1.683 1.682a2.414 2.414 0 0 1 0 3.414L19.61 15.39a1 1 0 0 1-1.68-.474 2.5 2.5 0 1 0-3.014 3.015 1 1 0 0 1 .474 1.68l-1.683 1.682a2.414 2.414 0 0 1-3.414 0L8.61 19.61a1 1 0 0 0-1.68.474 2.5 2.5 0 1 1-3.014-3.015 1 1 0 0 0 .474-1.68l-1.683-1.682a2.414 2.414 0 0 1 0-3.414L4.39 8.61a1 1 0 0 1 1.68.474 2.5 2.5 0 1 0 3.014-3.015 1 1 0 0 1-.474-1.68l1.683-1.682a2.414 2.414 0 0 1 3.414 0z"/>';

/** The markup of a whole icon, from either form. */
export function iconSvg(icon: string | undefined): string {
	const markup = icon?.trim() || PUZZLE;
	if (markup.startsWith('<svg')) return markup;
	return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${markup}</svg>`;
}
